#[derive(Debug, Clone)]
pub struct DescriptorLimits {
    pub max_json_bytes: usize,
    pub max_component_bytes: usize,
    pub max_manifest_files: usize,
    pub max_chunk_references: usize,
}
impl Default for DescriptorLimits {
    fn default() -> Self {
        Self {
            max_json_bytes: 65536,
            max_component_bytes: 134217728,
            max_manifest_files: 1024,
            max_chunk_references: 65536,
        }
    }
}
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct SceneFile {
    pub path: String,
    pub blake3: String,
    pub size: u64,
}
impl SceneFile {
    /// Hash caller-supplied generated bytes; this does not inspect GLB headers or geometry.
    pub fn from_bytes(path: &str, bytes: &[u8], limits: &DescriptorLimits) -> Result<Self> {
        ensure!(
            valid_path(path) && path != "scene.json",
            "invalid component path"
        );
        ensure!(
            !bytes.is_empty() && bytes.len() <= limits.max_component_bytes,
            "component byte limit exceeded"
        );
        Ok(Self {
            path: path.into(),
            blake3: Cas::hash(bytes),
            size: u64::try_from(bytes.len())?,
        })
    }
    fn validate(&self, limits: &DescriptorLimits) -> Result<()> {
        ensure!(
            valid_path(&self.path) && self.path != "scene.json",
            "invalid component path"
        );
        ensure!(valid_hash(&self.blake3), "invalid component BLAKE3");
        ensure!(
            self.size > 0 && self.size <= u64::try_from(limits.max_component_bytes)?,
            "component byte limit exceeded"
        );
        Ok(())
    }
}
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(
    tag = "availability",
    rename_all = "kebab-case",
    rename_all_fields = "camelCase",
    deny_unknown_fields
)]
pub enum VisualComponent {
    NotExtracted {},
    Unsupported {},
    Available {
        scope: String,
        file: SceneFile,
        requirements: ReaderRequirements,
    },
}
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(
    tag = "availability",
    rename_all = "kebab-case",
    rename_all_fields = "camelCase",
    deny_unknown_fields
)]
pub enum CollisionComponent {
    NotExtracted {},
    Unsupported {},
    Available {
        scope: String,
        file: SceneFile,
        requirements: ReaderRequirements,
        query_policy: InspectionQueryPolicy,
    },
    AvailableEmpty {
        scope: String,
        file: SceneFile,
        requirements: ReaderRequirements,
        query_policy: InspectionQueryPolicy,
    },
}
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct SceneComponents {
    pub visual: VisualComponent,
    pub collision: CollisionComponent,
}
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct SceneDescriptor {
    pub schema_version: u32,
    pub set: String,
    pub zone: String,
    pub scope: String,
    pub coordinate_profile: String,
    pub unit_scale: u32,
    pub bake_revision: String,
    pub requirements: ReaderRequirements,
    pub required_operations: Vec<String>,
    pub components: SceneComponents,
}
impl SceneDescriptor {
    pub fn new(
        zone: &str,
        bake_revision: &str,
        visual: VisualComponent,
        collision: CollisionComponent,
    ) -> Result<Self> {
        // Check borrowed identity strings before copying or formatting them.
        ensure!(token(zone), "invalid descriptor zone");
        ensure!(valid_hash(bake_revision), "invalid descriptor bakeRevision");
        let components = SceneComponents { visual, collision };
        let limits = DescriptorLimits::default();
        let capabilities = component_union(&components, &limits)?;
        let descriptor = Self {
            schema_version: 1,
            set: format!("zone/{zone}"),
            zone: zone.into(),
            scope: "declared-static-inspection-v1".into(),
            coordinate_profile: "eqoxide-static-y-up-v1".into(),
            unit_scale: 1,
            bake_revision: bake_revision.into(),
            requirements: ReaderRequirements {
                reader_version: 2,
                capabilities,
            },
            required_operations: vec![],
            components,
        };
        descriptor.validate(&limits)?;
        Ok(descriptor)
    }
    pub fn validate(&self, limits: &DescriptorLimits) -> Result<()> {
        ensure!(
            self.schema_version == 1,
            "unsupported descriptor schemaVersion"
        );
        ensure!(
            token(&self.zone) && self.set == format!("zone/{}", self.zone),
            "descriptor set/zone mismatch"
        );
        ensure!(
            self.scope == "declared-static-inspection-v1",
            "unsupported descriptor scope"
        );
        ensure!(
            self.coordinate_profile == "eqoxide-static-y-up-v1" && self.unit_scale == 1,
            "unsupported descriptor coordinate/unit profile"
        );
        ensure!(
            valid_hash(&self.bake_revision),
            "invalid descriptor bakeRevision"
        );
        ensure!(
            self.required_operations.is_empty(),
            "inspection descriptor has no required operations"
        );
        let expected = component_union(&self.components, limits)?;
        self.requirements.validate()?;
        ensure!(
            self.requirements.reader_version == 2 && self.requirements.capabilities == expected,
            "descriptor requirement union mismatch"
        );
        Ok(())
    }
}
impl SceneComponents {
    fn references(&self) -> impl Iterator<Item = (&SceneFile, &ReaderRequirements)> {
        let visual = match &self.visual {
            VisualComponent::Available {
                file, requirements, ..
            } => Some((file, requirements)),
            _ => None,
        };
        let collision = match &self.collision {
            CollisionComponent::Available {
                file, requirements, ..
            }
            | CollisionComponent::AvailableEmpty {
                file, requirements, ..
            } => Some((file, requirements)),
            _ => None,
        };
        visual.into_iter().chain(collision)
    }
}
fn role_requirements(
    requirements: &ReaderRequirements,
    required: &str,
    allowed: &[&str],
) -> Result<()> {
    requirements.validate()?;
    ensure!(
        requirements.reader_version == 2,
        "unsupported component reader contract"
    );
    let unique: BTreeSet<_> = requirements
        .capabilities
        .iter()
        .map(String::as_str)
        .collect();
    ensure!(
        unique.len() == requirements.capabilities.len(),
        "duplicate component capability"
    );
    ensure!(
        unique.contains(required) && unique.iter().all(|c| allowed.contains(c)),
        "unsupported component requirements"
    );
    Ok(())
}
fn component_union(components: &SceneComponents, limits: &DescriptorLimits) -> Result<Vec<String>> {
    if let VisualComponent::Available {
        scope,
        requirements,
        ..
    } = &components.visual
    {
        ensure!(
            scope == "declared-static-visual-scene-v1",
            "unsupported visual declared scope"
        );
        role_requirements(
            requirements,
            "static-visual-v1",
            &["static-visual-v1", "vertex-rgba-v1"],
        )?;
    }
    if let CollisionComponent::Available {
        scope,
        requirements,
        ..
    }
    | CollisionComponent::AvailableEmpty {
        scope,
        requirements,
        ..
    } = &components.collision
    {
        ensure!(
            scope == "declared-static-triangle-candidates-v1",
            "unsupported collision declared scope"
        );
        role_requirements(
            requirements,
            "static-collision-triangles-v1",
            &["static-collision-triangles-v1"],
        )?;
    }
    let mut paths = BTreeSet::new();
    let mut capabilities = BTreeSet::from(["static-scene-package-v1".to_string()]);
    for (file, requirements) in components.references() {
        file.validate(limits)?;
        ensure!(paths.insert(&file.path), "aliased component paths");
        capabilities.extend(requirements.capabilities.iter().cloned());
    }
    Ok(capabilities.into_iter().collect())
}
struct BoundedJson {
    bytes: Vec<u8>,
    limit: usize,
}
impl Write for BoundedJson {
    fn write(&mut self, bytes: &[u8]) -> io::Result<usize> {
        self.bytes
            .len()
            .checked_add(bytes.len())
            .filter(|end| *end <= self.limit)
            .ok_or_else(|| io::Error::other("descriptor JSON byte limit exceeded"))?;
        self.bytes.extend_from_slice(bytes);
        Ok(bytes.len())
    }
    fn flush(&mut self) -> io::Result<()> {
        Ok(())
    }
}
pub fn encode_scene_descriptor(
    descriptor: &SceneDescriptor,
    limits: &DescriptorLimits,
) -> Result<Vec<u8>> {
    descriptor.validate(limits)?;
    let mut output = BoundedJson {
        bytes: Vec::new(),
        limit: limits.max_json_bytes,
    };
    serde_json::to_writer(&mut output, descriptor).context("encode bounded scene descriptor")?;
    Ok(output.bytes)
}
pub fn decode_scene_descriptor(bytes: &[u8], limits: &DescriptorLimits) -> Result<SceneDescriptor> {
    ensure!(
        bytes.len() <= limits.max_json_bytes,
        "descriptor JSON byte limit exceeded"
    );
    let descriptor: SceneDescriptor =
        serde_json::from_slice(bytes).context("invalid scene descriptor JSON")?;
    descriptor.validate(limits)?;
    Ok(descriptor)
}
/// Atomically replace only the descriptor; no manifest or component transaction is performed.
pub fn write_scene_descriptor(
    descriptor: &SceneDescriptor,
    output: &Path,
    limits: &DescriptorLimits,
) -> Result<ReaderRequirements> {
    let bytes = encode_scene_descriptor(descriptor, limits)?;
    let parent = output
        .parent()
        .filter(|p| !p.as_os_str().is_empty())
        .unwrap_or_else(|| Path::new("."));
    let mut temp =
        tempfile::NamedTempFile::new_in(parent).context("create temporary scene descriptor")?;
    temp.write_all(&bytes)?;
    publish_static(temp, output, "scene descriptor")?;
    Ok(descriptor.requirements.clone())
}
/// Immutable proof of descriptor bytes and declared references bound to one manifest.
/// Component bytes/headers/geometry and current-world freshness are not verified here.
#[derive(Debug, Clone)]
pub struct DescriptorManifestBinding {
    descriptor: SceneDescriptor,
    manifest_revision: String,
    descriptor_blake3: String,
}
impl DescriptorManifestBinding {
    pub fn descriptor(&self) -> &SceneDescriptor {
        &self.descriptor
    }
    pub fn manifest_revision(&self) -> &str {
        &self.manifest_revision
    }
    pub fn descriptor_blake3(&self) -> &str {
        &self.descriptor_blake3
    }
}
fn charge_chunks(total: &mut usize, count: usize, limit: usize) -> Result<()> {
    *total = total
        .checked_add(count)
        .context("manifest chunk references overflow")?;
    ensure!(*total <= limit, "manifest chunk references limit exceeded");
    Ok(())
}
/// Bind strict metadata and actual descriptor bytes; performs no CAS or filesystem reads.
pub fn bind_scene_descriptor_to_manifest(
    bytes: &[u8],
    manifest: &Manifest,
    expected_zone: &str,
    limits: &DescriptorLimits,
) -> Result<DescriptorManifestBinding> {
    ensure!(
        bytes.len() <= limits.max_json_bytes,
        "descriptor JSON byte limit exceeded"
    );
    // These work bounds precede the existing manifest canonical serializer.
    ensure!(
        manifest.files.len() <= limits.max_manifest_files,
        "manifest file count exceeds limit"
    );
    let mut chunks = 0;
    for file in &manifest.files {
        charge_chunks(&mut chunks, file.chunks.len(), limits.max_chunk_references)?;
    }
    ensure!(token(expected_zone), "invalid requested zone");
    manifest.validate(&format!("zone/{expected_zone}"))?;
    let descriptor = decode_scene_descriptor(bytes, limits)?;
    ensure!(
        descriptor.zone == expected_zone && descriptor.set == manifest.set,
        "requested descriptor identity mismatch"
    );
    let mut paths = BTreeSet::from(["scene.json"]);
    for (file, _) in descriptor.components.references() {
        paths.insert(file.path.as_str());
    }
    ensure!(
        manifest.files.len() == paths.len()
            && manifest
                .files
                .iter()
                .all(|f| paths.contains(f.path.as_str())),
        "inspection manifest file membership mismatch"
    );
    let entry = manifest
        .files
        .iter()
        .find(|f| f.path == "scene.json")
        .context("scene.json missing from manifest")?;
    let descriptor_blake3 = Cas::hash(bytes);
    let descriptor_size = u64::try_from(bytes.len())?;
    ensure!(
        entry.blake3 == descriptor_blake3 && entry.size == descriptor_size,
        "descriptor byte identity mismatch"
    );
    for (reference, _) in descriptor.components.references() {
        let file = manifest
            .files
            .iter()
            .find(|f| f.path == reference.path)
            .context("component missing from manifest")?;
        ensure!(
            file.blake3 == reference.blake3 && file.size == reference.size,
            "declared component identity mismatch"
        );
    }
    let normalized: BTreeSet<_> = manifest.requirements.capabilities.iter().collect();
    let expected: BTreeSet<_> = descriptor.requirements.capabilities.iter().collect();
    ensure!(
        manifest.requirements.reader_version == 2 && normalized == expected,
        "manifest requirement union mismatch"
    );
    Ok(DescriptorManifestBinding {
        descriptor,
        manifest_revision: manifest.revision.clone(),
        descriptor_blake3,
    })
}
